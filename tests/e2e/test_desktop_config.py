class TestDesktopConfigTier1Features(unittest.TestCase):
    """Tier 1: Feature Coverage (Desktop Environment & Noise Silencing Core Tests)."""

    def setUp(self):
        self.notifyd_xml = find_artifact("configs/desktop/xfce4-notifyd.xml",
                                         "/etc/xdg/xfce4/xfconf/xfce-perchannel-xml/xfce4-notifyd.xml")
        self.nobeep_conf = find_artifact("configs/desktop/nobeep.conf", "/etc/modprobe.d/nobeep.conf")
        self.lightdm_conf = find_artifact("configs/desktop/lightdm-autologin.conf",
                                          "/etc/lightdm/lightdm.conf.d/50-autologin.conf")
        self.manifest_txt = find_artifact("configs/desktop/package_manifest.txt")

    def test_tier1_01_notifyd_xml_validity_and_dnd_locked(self):
        """Feature 12: xfce4-notifyd.xml must be valid XML with property do-not-disturb set to true."""
        if not self.notifyd_xml:
            self.skipTest("configs/desktop/xfce4-notifyd.xml not yet generated by Milestone 2")

        tree = ET.parse(str(self.notifyd_xml))
        root = tree.getroot()
        self.assertEqual(root.tag, "channel")
        self.assertEqual(root.get("name"), "xfce4-notifyd")

        # Find property with name="do-not-disturb"
        dnd_prop = None
        for prop in root.findall(".//property"):
            if prop.get("name") == "do-not-disturb":
                dnd_prop = prop
                break

        self.assertIsNotNone(dnd_prop, "Property 'do-not-disturb' not found in xfce4-notifyd.xml")
        self.assertEqual(dnd_prop.get("type"), "bool")
        self.assertEqual(dnd_prop.get("value", "").lower(), "true",
                         "do-not-disturb property value must be 'true'")

    def test_tier1_02_nobeep_conf_blacklists_pcspkr(self):
        """Feature 12: nobeep.conf must blacklist pcspkr to suppress the acoustic terminal bell."""
        if not self.nobeep_conf:
            self.skipTest("configs/desktop/nobeep.conf not yet generated by Milestone 2")

        content = self.nobeep_conf.read_text(encoding="utf-8")
        self.assertTrue(re.search(r'blacklist\s+pcspkr', content),
                        "nobeep.conf must contain 'blacklist pcspkr'")

    def test_tier1_03_lightdm_autologin_configured(self):
        """Feature 11: LightDM autologin must configure autologin-user and autologin-user-timeout=0."""
        if not self.lightdm_conf:
            self.skipTest("configs/desktop/lightdm-autologin.conf not yet generated by Milestone 2")

        parser = configparser.ConfigParser()
        parser.read_string(self.lightdm_conf.read_text(encoding="utf-8"))

        seat_section = None
        for sec in parser.sections():
            if sec.startswith("Seat:"):
                seat_section = sec
                break

        self.assertIsNotNone(seat_section, "LightDM autologin config must contain a [Seat:*] section")
        user = parser.get(seat_section, "autologin-user", fallback=None)
        timeout = parser.get(seat_section, "autologin-user-timeout", fallback=None)

        self.assertTrue(bool(user), "autologin-user must be defined")
        self.assertEqual(str(timeout), "0", "autologin-user-timeout must be 0 for instantaneous login")

    def test_tier1_04_package_manifest_excludes_games(self):
        """Feature 13: Package manifest must explicitly exclude or purge default games."""
        if not self.manifest_txt:
            self.skipTest("configs/desktop/package_manifest.txt not yet generated by Milestone 2")

        installed, excluded = parse_package_manifest(self.manifest_txt.read_text(encoding="utf-8"))
        for game in ["aisleriot", "gnome-mines", "gnome-sudoku", "mahjongg"]:
            self.assertIn(game, excluded, f"Default game '{game}' must be in excluded packages")
            self.assertNotIn(game, installed, f"Default game '{game}' must not be installed")

    def test_tier1_05_package_manifest_excludes_telemetry(self):
        """Feature 13: Package manifest must exclude crash reporting and telemetry services."""
        if not self.manifest_txt:
            self.skipTest("configs/desktop/package_manifest.txt not yet generated by Milestone 2")

        installed, excluded = parse_package_manifest(self.manifest_txt.read_text(encoding="utf-8"))
        for tel in ["whoopsie", "apport", "popularity-contest"]:
            self.assertIn(tel, excluded, f"Telemetry daemon '{tel}' must be in excluded packages")
            self.assertNotIn(tel, installed, f"Telemetry daemon '{tel}' must not be installed")

    def test_tier1_06_package_manifest_excludes_bloat_services(self):
        """Feature 13: Package manifest must exclude printing and network discovery daemons (cups, avahi)."""
        if not self.manifest_txt:
            self.skipTest("configs/desktop/package_manifest.txt not yet generated by Milestone 2")

        installed, excluded = parse_package_manifest(self.manifest_txt.read_text(encoding="utf-8"))
        for svc in ["cups", "avahi-daemon"]:
            self.assertIn(svc, excluded, f"Bloat daemon '{svc}' must be in excluded packages")
            self.assertNotIn(svc, installed, f"Bloat daemon '{svc}' must not be installed")

    def test_tier1_07_package_manifest_includes_minimal_xfce(self):
        """Feature 11: Package manifest must include minimal XFCE desktop components."""
        if not self.manifest_txt:
            self.skipTest("configs/desktop/package_manifest.txt not yet generated by Milestone 2")

        installed, excluded = parse_package_manifest(self.manifest_txt.read_text(encoding="utf-8"))
        core_xfce = ["xfce4-session", "xfwm4", "xfce4-panel", "xfdesktop4", "thunar"]
        for pkg in core_xfce:
            self.assertIn(pkg, installed, f"Core XFCE component '{pkg}' must be installed")


class TestDesktopConfigTier2Boundaries(unittest.TestCase):
    """Tier 2: Boundary & Corner Cases (XML schema, snapd exclusion, LightDM session)."""

    def setUp(self):
        self.notifyd_xml = find_artifact("configs/desktop/xfce4-notifyd.xml",
                                         "/etc/xdg/xfce4/xfconf/xfce-perchannel-xml/xfce4-notifyd.xml")
        self.manifest_txt = find_artifact("configs/desktop/package_manifest.txt")
        self.lightdm_conf = find_artifact("configs/desktop/lightdm-autologin.conf",
                                          "/etc/lightdm/lightdm.conf.d/50-autologin.conf")

    def test_tier2_01_notifyd_xml_channel_and_structure(self):
        """Boundary: Validate xfce4-notifyd XML has version attribute and muted sound props."""
        if not self.notifyd_xml:
            self.skipTest("xfce4-notifyd.xml not yet generated")

        tree = ET.parse(str(self.notifyd_xml))
        root = tree.getroot()
        self.assertTrue("version" in root.attrib or len(root) > 0,
                        "xfce4-notifyd.xml channel must define properties")

    def test_tier2_02_manifest_snapd_exclusion(self):
        """Boundary: Validate that snapd is excluded to ensure live RAM efficiency."""
        if not self.manifest_txt:
            self.skipTest("package_manifest.txt not yet generated")

        installed, excluded = parse_package_manifest(self.manifest_txt.read_text(encoding="utf-8"))
        self.assertIn("snapd", excluded, "snapd must be explicitly excluded from minimal live OS")
        self.assertNotIn("snapd", installed)

    def test_tier2_03_lightdm_session_directive(self):
        """Boundary: Validate LightDM autologin specifies autologin-session=xfce."""
        if not self.lightdm_conf:
            self.skipTest("lightdm-autologin.conf not yet generated")

        content = self.lightdm_conf.read_text(encoding="utf-8")
        self.assertTrue("autologin-session" in content or "user-session" in content or "xfce" in content,
                        "LightDM config must specify xfce session")

    def test_tier2_04_nobeep_conf_idempotent_syntax(self):
        """Boundary: Validate nobeep.conf syntax has no malformed directives."""
        nobeep_conf = find_artifact("configs/desktop/nobeep.conf")
        if not nobeep_conf:
            self.skipTest("nobeep.conf not yet generated")

        lines = [line.strip() for line in nobeep_conf.read_text(encoding="utf-8").splitlines()]
        for line in lines:
            if not line or line.startswith("#"):
                continue
            self.assertTrue(line.startswith("blacklist") or line.startswith("install"),
                            f"Unexpected directive in nobeep.conf: {line}")

    def test_tier2_05_corrupt_xml_error_handling(self):
        """Boundary: Invalidate corrupted XML to ensure test suite detects malformed configs."""
        bad_xml = "<channel><property name='do-not-disturb' value='true'></channel>"
        with self.assertRaises(ET.ParseError):
            ET.fromstring(bad_xml)


