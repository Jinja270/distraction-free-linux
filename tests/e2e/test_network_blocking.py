class TestNetworkBlockingTier2Boundaries(unittest.TestCase):
    """Tier 2: Boundary & Corner Cases (Dual-stack, subdomains, case sensitivity, VPN ports)."""

    def setUp(self):
        self.hosts_path = find_artifact("configs/network/hosts.blocklist", "/etc/hosts")
        self.nftables_path = find_artifact("configs/network/nftables.conf", "/etc/nftables.conf")

    def test_tier2_01_ipv4_and_ipv6_parity_audit(self):
        """Boundary: Assert 100% parity between IPv4 and IPv6 blocklist entries (no orphaned A/AAAA)."""
        if not self.hosts_path:
            self.skipTest("configs/network/hosts.blocklist not yet generated by Milestone 1")

        content = self.hosts_path.read_text(encoding="utf-8")
        domain_to_ips = parse_hosts_file(content)

        orphaned_v4_only = []
        orphaned_v6_only = []

        for domain, ips in domain_to_ips.items():
            has_v4 = "0.0.0.0" in ips or "127.0.0.1" in ips
            has_v6 = "::" in ips or "::1" in ips
            if has_v4 and not has_v6:
                orphaned_v4_only.append(domain)
            elif has_v6 and not has_v4:
                orphaned_v6_only.append(domain)

        self.assertEqual(orphaned_v4_only, [], f"Domains with IPv4 sinkhole missing IPv6: {orphaned_v4_only[:5]}")
        self.assertEqual(orphaned_v6_only, [], f"Domains with IPv6 sinkhole missing IPv4: {orphaned_v6_only[:5]}")

    def test_tier2_02_subdomain_and_www_coverage_consistency(self):
        """Boundary: Assert that primary domains have their www / m / web subdomains blocked."""
        if not self.hosts_path:
            self.skipTest("configs/network/hosts.blocklist not yet generated by Milestone 1")

        content = self.hosts_path.read_text(encoding="utf-8")
        domain_to_ips = parse_hosts_file(content)

        key_domains = [
            ("reddit.com", "www.reddit.com"),
            ("reddit.com", "old.reddit.com"),
            ("youtube.com", "www.youtube.com"),
            ("youtube.com", "m.youtube.com"),
            ("facebook.com", "www.facebook.com"),
            ("twitter.com", "www.twitter.com"),
            ("x.com", "www.x.com"),
        ]

        missing_subdomains = []
        for root, sub in key_domains:
            if root in domain_to_ips and sub not in domain_to_ips:
                missing_subdomains.append(sub)

        self.assertEqual(missing_subdomains, [], f"Missing required subdomains for blocked services: {missing_subdomains}")

    def test_tier2_03_hosts_case_insensitivity_and_formatting(self):
        """Boundary: Assert no uppercase domains and no malformed IP addresses in hosts.blocklist."""
        if not self.hosts_path:
            self.skipTest("configs/network/hosts.blocklist not yet generated by Milestone 1")

        lines = self.hosts_path.read_text(encoding="utf-8").splitlines()
        malformed_lines = []
        uppercase_domains = []

        for idx, line in enumerate(lines, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 2:
                malformed_lines.append((idx, line))
                continue
            ip = parts[0]
            if not is_valid_ip(ip):
                malformed_lines.append((idx, line))
            for dom in parts[1:]:
                if any(c.isupper() for c in dom):
                    uppercase_domains.append((idx, dom))

        self.assertEqual(malformed_lines, [], f"Malformed lines found in hosts.blocklist: {malformed_lines[:5]}")
        self.assertEqual(uppercase_domains, [], f"Uppercase characters in hosts domains: {uppercase_domains[:5]}")

    def test_tier2_04_nftables_table_chain_and_loopback_policy(self):
        """Boundary: Validate nftables defines table inet filter, loopback acceptance, and default drop."""
        if not self.nftables_path:
            self.skipTest("configs/network/nftables.conf not yet generated by Milestone 1")

        content = self.nftables_path.read_text(encoding="utf-8")
        self.assertTrue("table inet filter" in content or "table ip filter" in content or "table inet" in content,
                        "nftables.conf must declare a valid inet filter table")
        self.assertTrue("chain output" in content, "nftables.conf must define an output chain")
        self.assertTrue("iif \"lo\" accept" in content or "iifname \"lo\" accept" in content or "oif \"lo\" accept" in content or "oifname \"lo\" accept" in content,
                        "nftables.conf must accept loopback traffic")

    def test_tier2_05_nftables_vpn_tunnel_port_blocking(self):
        """Boundary: Validate nftables firewall drops unauthorized VPN tunnel ports (OpenVPN 1194, WireGuard 51820)."""
        if not self.nftables_path:
            self.skipTest("configs/network/nftables.conf not yet generated by Milestone 1")

        content = self.nftables_path.read_text(encoding="utf-8")
        # Check for 1194 (OpenVPN) and 51820 (WireGuard)
        has_1194 = "1194" in content
        has_51820 = "51820" in content
        self.assertTrue(has_1194 or has_51820 or "vpn_ports" in content,
                        "nftables.conf must block unauthorized VPN tunnel ports (1194, 51820)")

    def test_tier2_06_nftables_conntrack_state_integrity(self):
        """Boundary: Validate nftables includes stateful inspection (ct state {established, related} accept)."""
        if not self.nftables_path:
            self.skipTest("configs/network/nftables.conf not yet generated by Milestone 1")

        content = self.nftables_path.read_text(encoding="utf-8")
