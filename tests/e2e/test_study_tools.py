    def _get_launcher(self, name: str) -> Path:
        p = self.launchers_dir / f"{name}.desktop"
        if p.is_file():
            return p
        sys_p = Path(f"/usr/share/applications/{name}.desktop")
        if sys_p.is_file():
            return sys_p
        return None

