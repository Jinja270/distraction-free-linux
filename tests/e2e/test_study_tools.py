class TestStudyToolsTier2Boundaries(unittest.TestCase):
    """Tier 2: Boundary & Corner Cases (Timer intervals, silent alerts, desktop key validation)."""

    def setUp(self):
        self.pomodoro_script = find_artifact("scripts/pomodoro_timer.py", "/usr/local/bin/pomodoro_timer.py")
        self.launchers_dir = PROJECT_ROOT / "configs" / "desktop" / "launchers"

    def test_tier2_01_pomodoro_standard_intervals(self):
        """Boundary: Pomodoro timer script must define 25m work, 5m short break, and 15m long break."""
        if not self.pomodoro_script:
            self.skipTest("pomodoro_timer.py not yet generated")

        content = self.pomodoro_script.read_text(encoding="utf-8")
        # Check for 25 (or 1500s), 5 (or 300s), 15 (or 900s)
        has_work = "25" in content or "1500" in content
        has_break = "5" in content or "300" in content
        self.assertTrue(has_work and has_break, "Pomodoro timer must define standard 25m study and 5m break intervals")

    def test_tier2_02_pomodoro_timer_silent_operation(self):
        """Boundary: Pomodoro timer must NOT execute audio commands (respecting zero acoustic noise)."""
        if not self.pomodoro_script:
            self.skipTest("pomodoro_timer.py not yet generated")

        content = self.pomodoro_script.read_text(encoding="utf-8")
        audio_commands = ["paplay", "aplay", "mpg123", "play_sound", "\a", "\\a"]
        detected_audio = [cmd for cmd in audio_commands if cmd in content]
        self.assertEqual(detected_audio, [], f"Pomodoro timer must be silent, but found audio calls: {detected_audio}")

    def test_tier2_03_all_desktop_entries_have_required_keys(self):
        """Boundary: Assert that all launcher files contain Name, Exec, Type, and Icon keys."""
        if not self.launchers_dir.is_dir():
            self.skipTest("configs/desktop/launchers/ directory not yet created")

        launcher_files = list(self.launchers_dir.glob("*.desktop"))
        if not launcher_files:
            self.skipTest("No .desktop files present in launchers directory yet")

        required_keys = ["name", "exec", "type"]
        for l_file in launcher_files:
            entry = parse_desktop_entry(l_file.read_text(encoding="utf-8"))
            for k in required_keys:
                self.assertIn(k, entry, f"{l_file.name} missing mandatory key '{k}'")

    def test_tier2_04_zathurarc_minimal_ui_geometry(self):
        """Boundary: zathurarc must configure recolor or dark mode options for eye comfort."""
        zathurarc = find_artifact("configs/desktop/zathurarc")
        if not zathurarc:
            self.skipTest("zathurarc not yet generated")

        content = zathurarc.read_text(encoding="utf-8")
        has_recolor = "recolor" in content or "default-bg" in content or "statusbar-bg" in content
        self.assertTrue(has_recolor, "zathurarc should specify recolor or dark background options")

    def test_tier2_05_manifest_declares_study_tools(self):
        """Boundary: package_manifest.txt must declare study tool packages."""
        manifest = find_artifact("configs/desktop/package_manifest.txt")
        if not manifest:
            self.skipTest("package_manifest.txt not yet generated")

        installed, excluded = parse_package_manifest(manifest.read_text(encoding="utf-8"))
        for tool in ["evince", "zathura", "focuswriter"]:
            self.assertIn(tool, installed, f"Manifest must list '{tool}' in installed packages")


class TestStudyToolsTier3Combinations(unittest.TestCase):
    """Tier 3: Cross-Feature Combinations (Tooling co-existence and launcher integration)."""

    def test_tier3_01_zathura_and_evince_coexistence(self):
        """Combination: Both Evince and Zathura launchers exist with distinct roles."""
        launchers_dir = PROJECT_ROOT / "configs" / "desktop" / "launchers"
        evince_l = launchers_dir / "evince.desktop"
        zathura_l = launchers_dir / "zathura.desktop"

        if not evince_l.is_file() or not zathura_l.is_file():
            self.skipTest("Evince and Zathura launchers not yet generated")

        ev_entry = parse_desktop_entry(evince_l.read_text(encoding="utf-8"))
        za_entry = parse_desktop_entry(zathura_l.read_text(encoding="utf-8"))

        self.assertNotEqual(ev_entry.get("exec"), za_entry.get("exec"),
                            "Evince and Zathura must have distinct Exec commands")

    def test_tier3_02_pomodoro_launcher_and_executable_alignment(self):
        """Combination: pomodoro.desktop Exec matches pomodoro_timer.py script path."""
        p_desktop = PROJECT_ROOT / "configs" / "desktop" / "launchers" / "pomodoro.desktop"
        if not p_desktop.is_file():
            self.skipTest("pomodoro.desktop not yet generated")

        entry = parse_desktop_entry(p_desktop.read_text(encoding="utf-8"))
        exec_cmd = entry.get("exec", "")
        self.assertTrue("pomodoro_timer.py" in exec_cmd or "pomodoro" in exec_cmd,
                        f"pomodoro.desktop Exec must invoke pomodoro timer script, got: {exec_cmd}")


