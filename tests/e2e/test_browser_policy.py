class TestBrowserPolicyTier1Features(unittest.TestCase):
    """Tier 1: Feature Coverage (Browser Lockdown Core Policies)."""

    def setUp(self):
        self.policy_path = find_artifact("configs/browser/policies.json", "/etc/firefox/policies/policies.json")

    def _get_policies(self):
        if not self.policy_path:
            self.skipTest("configs/browser/policies.json not yet generated by Milestone 1")
        try:
            data = json.loads(self.policy_path.read_text(encoding="utf-8"))
            return data.get("policies", {})
        except Exception as e:
            self.fail(f"Failed to parse policies.json: {e}")

    def test_tier1_01_policies_json_valid_json_schema(self):
        """Feature 8: policies.json must exist and parse as valid JSON with top-level 'policies' key."""
        policies = self._get_policies()
        self.assertIsInstance(policies, dict, "Top-level JSON must contain 'policies' dictionary")
        self.assertGreater(len(policies), 0, "'policies' dictionary must not be empty")

    def test_tier1_02_doh_disabled_and_locked(self):
        """Feature 8: DNSOverHTTPS must be explicitly disabled and locked (network.trr.mode = 5)."""
        policies = self._get_policies()
        doh = policies.get("DNSOverHTTPS", {})
        self.assertIsInstance(doh, dict, "DNSOverHTTPS must be a dictionary")
        self.assertFalse(doh.get("Enabled", True), "DNSOverHTTPS Enabled must be false")
        self.assertTrue(doh.get("Locked", False), "DNSOverHTTPS Locked must be true")

    def test_tier1_03_proxy_locked_to_system(self):
        """Feature 8: Proxy configuration must be locked to system mode to prevent proxy bypass."""
        policies = self._get_policies()
        proxy = policies.get("Proxy", {})
        self.assertIsInstance(proxy, dict, "Proxy must be a dictionary")
        self.assertIn(str(proxy.get("Mode", "")).lower(), ["system", "none", "0"],
                      "Proxy Mode must be 'system' or 'none'")
        self.assertTrue(proxy.get("Locked", False), "Proxy Locked must be true")

    def test_tier1_04_extension_install_blocked(self):
        """Feature 8: Extension installation must be globally blocked via ExtensionSettings."""
        policies = self._get_policies()
        ext_settings = policies.get("ExtensionSettings", {})
        self.assertIsInstance(ext_settings, dict, "ExtensionSettings must be a dictionary")
        wildcard_rule = ext_settings.get("*", {})
        install_mode = wildcard_rule.get("installation_mode", "")
        self.assertIn(install_mode.lower(), ["blocked", "restricted"],
                      "Global extension installation_mode must be 'blocked'")

    def test_tier1_05_private_browsing_and_devtools_locked(self):
        """Feature 8: Private browsing and developer tools must be disabled to prevent evasion."""
        policies = self._get_policies()
        self.assertTrue(policies.get("DisablePrivateBrowsing", False),
                        "DisablePrivateBrowsing must be true")
        self.assertTrue(policies.get("DisableDeveloperTools", False),
                        "DisableDeveloperTools must be true")

    def test_tier1_06_website_filter_blocks_distractions(self):
        """Feature 8: WebsiteFilter must block social media, video streaming, and gaming domains."""
        policies = self._get_policies()
        wf = policies.get("WebsiteFilter", {})
        block_list = wf.get("Block", [])
        self.assertIsInstance(block_list, list, "WebsiteFilter.Block must be a list of URL patterns")
        self.assertGreater(len(block_list), 0, "WebsiteFilter.Block must contain blocked patterns")

        block_str = " ".join(block_list)
        for target in ["reddit", "youtube", "twitter", "tiktok", "instagram"]:
            self.assertIn(target, block_str, f"WebsiteFilter.Block must cover {target}")

    def test_tier1_07_website_filter_whitelists_study_tools(self):
        """Feature 9: WebsiteFilter.Exceptions must explicitly permit ChatGPT, Claude, NotebookLM, Scholar, Wikipedia."""
        policies = self._get_policies()
        wf = policies.get("WebsiteFilter", {})
        exceptions = wf.get("Exceptions", [])
        self.assertIsInstance(exceptions, list, "WebsiteFilter.Exceptions must be a list of URL patterns")

        exc_str = " ".join(exceptions)
        for target in ["chatgpt.com", "claude.ai", "notebooklm.google.com", "wikipedia.org", "scholar.google.com"]:
            self.assertIn(target, exc_str, f"WebsiteFilter.Exceptions must permit {target}")

    def test_tier1_08_telemetry_and_sync_disabled(self):
        """Feature 8: Background telemetry, studies, and Pocket must be disabled in Firefox."""
        policies = self._get_policies()
        self.assertTrue(policies.get("DisableTelemetry", False), "DisableTelemetry must be true")
        self.assertTrue(policies.get("DisableFirefoxStudies", False), "DisableFirefoxStudies must be true")


class TestBrowserPolicyTier2Boundaries(unittest.TestCase):
    """Tier 2: Boundary & Corner Cases (URI syntax, Turnstile/CDN exceptions, password manager)."""

    def setUp(self):
        self.policy_path = find_artifact("configs/browser/policies.json", "/etc/firefox/policies/policies.json")

    def _get_policies(self):
        if not self.policy_path:
            self.skipTest("configs/browser/policies.json not yet generated by Milestone 1")
        return json.loads(self.policy_path.read_text(encoding="utf-8")).get("policies", {})

    def test_tier2_01_uri_match_patterns_validity(self):
        """Boundary: Verify all URL patterns in WebsiteFilter follow valid Firefox match pattern syntax."""
        policies = self._get_policies()
        wf = policies.get("WebsiteFilter", {})
        all_patterns = wf.get("Block", []) + wf.get("Exceptions", [])

        invalid_patterns = []
        for pat in all_patterns:
            # Firefox Enterprise WebsiteFilter requires patterns like <scheme>://<host>/<path>
            # Valid schemes: http, https, ftp, or *
            if not re.match(r'^(\*|https?|ftp)://[^/]+(/.*)?$', pat):
                invalid_patterns.append(pat)

        self.assertEqual(invalid_patterns, [], f"Invalid WebsiteFilter pattern syntax: {invalid_patterns[:5]}")

    def test_tier2_02_no_whitelist_blocklist_overlap(self):
        """Boundary: Ensure no study tools in Exceptions are accidentally listed in Block list."""
        policies = self._get_policies()
        wf = policies.get("WebsiteFilter", {})
        blocks = set(wf.get("Block", []))
        exceptions = set(wf.get("Exceptions", []))

        overlap = blocks.intersection(exceptions)
        self.assertEqual(overlap, set(), f"Ambiguous rule overlap between Block and Exceptions: {overlap}")

    def test_tier2_03_turnstile_and_cdn_patterns_in_exceptions(self):
        """Boundary: Verify OpenAI/Claude CDNs and Cloudflare Turnstile captcha are present in Exceptions."""
        policies = self._get_policies()
        wf = policies.get("WebsiteFilter", {})
        exc_str = " ".join(wf.get("Exceptions", []))

        critical_patterns = [
            "challenges.cloudflare.com",
            "oaistatic.com",
            "assets.claude.ai",
        ]
        missing = [pat for pat in critical_patterns if pat not in exc_str]
        self.assertEqual(missing, [], f"Critical auth/captcha patterns missing in browser exceptions: {missing}")

    def test_tier2_04_password_manager_disabled(self):
        """Boundary: Assert password saving prompts and autofill are turned off for study privacy."""
        policies = self._get_policies()
        pass_off = policies.get("PasswordManagerEnabled") is False or policies.get("OfferToSaveLogins") is False
        self.assertTrue(pass_off, "PasswordManagerEnabled or OfferToSaveLogins must be false")

    def test_tier2_05_pocket_and_sponsored_shortcuts_disabled(self):
        """Boundary: Pocket and sponsored new tab shortcuts must be suppressed."""
        policies = self._get_policies()
        self.assertTrue(policies.get("DisablePocket", False) or "pocket" in json.dumps(policies).lower(),
                        "Pocket or sponsored suggestions must be disabled in policies.json")

    def test_tier2_06_corrupt_json_resilience(self):
        """Boundary: Verify JSON parser catches malformed syntax cleanly without silent failures."""
        malformed_json = '{"policies": {"DNSOverHTTPS": {"Enabled": false, }}}'
        with self.assertRaises(json.JSONDecodeError):
            json.loads(malformed_json)


class TestBrowserPolicyTier3Combinations(unittest.TestCase):
    """Tier 3: Cross-Feature Combinations (Browser policy paired with network configuration)."""

    def setUp(self):
        self.policy_path = find_artifact("configs/browser/policies.json", "/etc/firefox/policies/policies.json")
        self.hosts_path = find_artifact("configs/network/hosts.blocklist", "/etc/hosts")

    def test_tier3_01_browser_website_filter_mirrors_hosts_blocklist(self):
        """Combination: Verify that social media blocked in /etc/hosts is also blocked in Firefox WebsiteFilter."""
        if not self.policy_path or not self.hosts_path:
            self.skipTest("Milestone 1 artifacts not yet generated")

        policies = json.loads(self.policy_path.read_text(encoding="utf-8")).get("policies", {})
        wf = policies.get("WebsiteFilter", {})
        block_str = " ".join(wf.get("Block", []))

        hosts_content = self.hosts_path.read_text(encoding="utf-8")
        domain_to_ips = parse_hosts_file(hosts_content)

        # Reddit, YouTube, TikTok should be in both
        for domain in ["reddit.com", "youtube.com", "tiktok.com"]:
            self.assertIn(domain, domain_to_ips, f"{domain} must be in hosts")
            self.assertIn(domain, block_str, f"{domain} must be in browser WebsiteFilter")

    def test_tier3_02_doh_lockdown_forces_nsswitch_hosts_resolution(self):
        """Combination: DoH Locked=true guarantees browser cannot circumvent /etc/hosts sinkholes."""
        if not self.policy_path:
            self.skipTest("policies.json not yet generated")

        policies = json.loads(self.policy_path.read_text(encoding="utf-8")).get("policies", {})
        doh = policies.get("DNSOverHTTPS", {})
        self.assertTrue(doh.get("Locked") is True and doh.get("Enabled") is False,
                        "DoH locked off is mandatory to ensure libc getaddrinfo() /etc/hosts takes effect")

    def test_tier3_03_extension_block_stops_proxy_vpn_plugins(self):
        """Combination: Extension block prevents students from installing proxy switcher extensions."""
        if not self.policy_path:
            self.skipTest("policies.json not yet generated")

        policies = json.loads(self.policy_path.read_text(encoding="utf-8")).get("policies", {})
        ext_settings = policies.get("ExtensionSettings", {})
        self.assertEqual(ext_settings.get("*", {}).get("installation_mode"), "blocked",
                         "Wildcard extension installation must be blocked to prevent proxy/VPN extension bypass")


